# الإعراب: مشغل الخلية الأخيرة (مبرهنة ONTOLOGY-4)
IIRAB = {"رفع": "ضم", "نصب": "فتح", "جر": "كسر", "جزم": "سكون"}
def iirab(w, case):
    eps = IIRAB[case]
    nw = w[:-1] + [(w[-1][0], eps)]
    assert licensed(nw) or case == "جزم", f"i'rab theorem violated: {case}"
    return nw

# المواءمة ρ: دور الخلية الساكنة من (الحامل، حركة سابقها)
MADD = {"ا": "فتح", "و": "ضم", "ي": "كسر"}
def rho(cell, prev_state):
    c, s = cell
    if s == "سكون" and c in MADD:
        return "مد" if prev_state == MADD[c] else "إغلاق"
    return "سكون-صرفي"

