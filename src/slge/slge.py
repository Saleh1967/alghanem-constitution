def _key(w): return tuple(x for c,s in w for x in (c,s))

def attach(w, affix):
    j = w + list(affix)
    return j if licensed(j) else None

def classify(w):  # الخانتان: حرف معلن ⇐ زائد + هيكل/حرف معلن
    if _key(w) in PARTICLES: return ("bin1", w)
    for aff in PREFIX:
        aff = [tuple(x) for x in aff]
        if len(w) > len(aff) and w[:len(aff)] == aff:
            rest = w[len(aff):]
            if _key(rest) in PARTICLES or skeleton_match(rest):
                return ("bin1", rest)
    if skeleton_match(w):
        return ("bin1", w)
    return ("bin2", w)

def skeleton_match(w):  # هل النمط من أنماط الجرد المعلنة (أفعال + مصادر + ممنوع + جمع نواة)؟
    pat = "".join("M" if s != "سكون" else "S" for _, s in w)
    PATS = {"MMM","MSMM","MMSMM","MSMMM","MSMSM","MSMSMM",   # شبكة الأفعال I-X + Q
            "MSM","MMSM","MSMS","MMSMSM",                    # مصادر/ممنوع نواة (فَعْل، فُعُول، مَفْعِل، فِعَالَة)
            "MMSMS","MMMSM","MMMS"}                          # جمع/نواسخ نواة
    return licensed(w) and pat in PATS

def count(n):  # عدّاد المرخص: U = 29^n · f
    a, b = 1, 87
    for _ in range(n):
        a, b = b, 87 * b + 2523 * a
    return a

