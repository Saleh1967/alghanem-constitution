import slge

A = slge.ALPHABET
# الأزواج العشرة: (الصف، ضده، حملته الموجبة، بينيّاته)
PAIRS = [
 ("جهر",  "همس",   [c for c in A if c not in "فحثهشخسكت"], []),
 ("همس",  "جهر",   list("فحثهشخسكت"), []),
 ("شدة",  "رخاوة", list("بجدطعقكء"), []),
 ("رخاوة","شدة",   [c for c in A if c not in "بجدطعقكء"], []),
 ("استعلاء","استفال", list("خصضغطقظ"), ["ل"]),
 ("استفال","استعلاء",[c for c in A if c not in "خصضغطقظ" and c != "ل"], []),
 ("إطباق","انفتاح", list("صضطظق"), []),
 ("انفتاح","إطباق", [c for c in A if c not in "صضطظق"], []),
 ("ذلاقة","إصمات", list("فبمولنر"), []),
 ("إصمات","ذلاقة", [c for c in A if c not in "فبمولنر"], []),
 ("غنة",  "لين",   list("نم"), []),
 ("لين",  "غنة",   ["و","ي"], ["و","ي"]),
 ("تفشي","جمعة",  list("ش"), []),
 ("جمعة","تفشي",  [c for c in A if c != "ش"], []),
 ("اصطرار","انحراف", list("ر"), []),
 ("انحراف","اصطرار", list("ل"), []),
]
BETWEEN = {"ل": "استعلاء/استفال بيني", "و": "لين/توسط", "ي": "لين/توسط"}
# المخارج: (المكان، التفصيل) — خمسة أماكن، سبعة عشر مخرجًا معلنًا
MAHRAJ = {}
for c in A: MAHRAJ[c] = ("اللسان", "عام")
MAHRAJ.update({"ا": ("الجوف", "أقصى/أدنى: مدّ الفتح"), "و": ("الجوف", "أوسط: مدّ الضم"), "ي": ("الجوف", "أقصى: مدّ الكسر"),
 "ء": ("الحلق", "أقصى"), "ه": ("الحلق", "أدنى"), "ع": ("الحلق", "وسط"), "ح": ("الحلق", "وسط"),
 "غ": ("الحلق", "أدنى"), "خ": ("الحلق", "أدنى"),
 "ق": ("اللسان", "أقصى ما يلي الحلق"), "ك": ("اللسان", "أقصى ما يلي الظهر"),
 "ج": ("اللسان", "وسط فوق"), "ش": ("اللسان", "وسط فوق"), "ي2": ("اللسان", "وسط فوق"),
 "ض": ("اللسان", "حافة مع أطراف الثنايا"), "ل": ("اللسان", "طرف أدناه"), "ن": ("اللسان", "طرف أدنى"),
 "ر": ("اللسان", "طرف أعلاه"), "ط": ("اللسان", "أدنى مع أطراف"), "د": ("اللسان", "أدنى مع أطراف"),
 "ت": ("اللسان", "أدنى مع أطراف"), "ص": ("اللسان", "أدنى مع أصول"), "س": ("اللسان", "أدنى مع أصول"),
 "ز": ("اللسان", "أدنى مع أصول"), "ظ": ("اللسان", "أدنى مع وسط"),
 "ف": ("الشفتان", "مخرج فم"), "ب": ("الشفتان", "مخرج فم"), "م": ("الشفتان", "مخرج فم"),
 "ن": ("الخيشوم", "غنة"), "م2": ("الخيشوم", "غنة أشد")})

def features(c):
    f = {}
    for name, opp, pos, bet in PAIRS:
        f[name] = "+" if c in pos else ("بيني" if c in bet else "-")
    return f

if __name__ == "__main__":
    ok = True
    # Q18: كل حرفٍ متجهُ صفاتٍ كامل (الأزواج العشرة محسومة أو بينيّة معلنة)
    q18 = all(all(features(c)[p[0]] in ("+", "-", "بيني") for p in PAIRS) for c in A)
    ok &= q18; print(f"  {'✓' if q18 else '⛔'} Q18 الصفات تسبق الأبجدية: 29 متجهًا كاملًا")
