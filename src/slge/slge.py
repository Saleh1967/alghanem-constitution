def conjugate(root, tense, person):  # root حروف ثلاثية
    f, e, l = root
    if tense == "ماضٍ":
        w = [(f,"فتح"),(e,"فتح"),(l,"فتح")]
        for c, s in MADI_SUFFIX[person]: w = w + [(c,s)]
    else:
        w = [(c,s) for c,s in MUZARA_PREFIX[person]] + [(f,"سكون"),(e,"ضم"),(l,"ضم")]
        for c, s in MUZARA_SUFFIX[person]: w = w + [(c,s)]
    assert licensed(w), (root, tense, person)
    return w

