def licensed(w):
    return w[0][1] != "سكون" and all(
        not (w[i][1] == "سكون" and w[i + 1][1] == "سكون")
        for i in range(len(w) - 1))

def wasl_join(a, b):  # قانون الوصل + المسلّمة 5 (همزة الوصل وحدها)
    b = list(b)
    if b and b[0] == ("ا", "سكون"):
        b = b[1:]
    return list(a) + b

def W(w):  # قانون الوقف: ختام→سكون، نون التنوين، نون الوقاية وألفها
    w = list(w)
    if w[-1] == ("ن", "سكون") and len(w) > 1 and w[-2][1] != "سكون":
        return w[:-2] + [(w[-2][0], "سكون")]
    if w[-1][0] == "ن" and len(w) >= 2 and w[-2][0] in "وا":
        return w[:-2]
    return w[:-1] + [(w[-1][0], "سكون")] if w[-1][1] != "سكون" else w

def T(w):  # التنوين (قانون 1.8): + (ن، سكون) على الخاتم المتحرك
    return w + [("ن", "سكون")]

